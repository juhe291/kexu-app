package com.kexu.app.domain.imports

/** 供其他学校用户导出给 AI 的导入模板与提示词；格式与 CSV 导入器一致。 */
object ImportTemplates {

    const val FIELDS = "课程名,教师,地点,星期,开始节次,结束节次,周次,单双周"

    fun csvTemplate(): String = buildString {
        appendLine(FIELDS)
        appendLine("高等数学,张老师,公教2-509,周一,1,2,1-16,")
        appendLine("大学英语3,李老师,公教1-106,周三,3,4,\"1-5,7-11\",")
        appendLine("篮球初级班,王老师,田径场,周五,5,6,\"5-7周(单),8-16周\",")
        appendLine("// 说明：星期支持 周一/星期一/1；节次用数字；周次支持 1-16、1-5,7-11、单周(5-7周(单))、双周(4-6周(双))")
    }

    fun jsonTemplate(): String = """
        {
          "schema": "kexu-timetable/v1",
          "semester": { "startDate": "2026-09-07", "totalWeeks": 20 },
          "weekdayNote": "weekday 用 1-7，1=周一、2=周二 … 7=周日；weeks 用教学周表达式，如 1-16、1-5,7-11、1-8周(单)",
          "courses": [
            {
              "name": "高等数学",
              "teacher": "张老师",
              "room": "公教2-509",
              "meetings": [
                { "weekday": 1, "startPeriod": 1, "endPeriod": 2, "weeks": "1-16" },
                { "weekday": 3, "startPeriod": 3, "endPeriod": 4, "weeks": "1-5,7-11" }
              ]
            },
            {
              "name": "篮球初级班",
              "teacher": "王老师",
              "room": "田径场",
              "meetings": [
                { "weekday": 5, "startPeriod": 5, "endPeriod": 6, "weeks": "5-7周(单),8-16周" }
              ]
            }
          ]
        }
    """.trimIndent()

    fun aiPromptTemplate(): String = """
        # 课序课表导入模板（请按此格式输出）

        我会提供一张/一份学校教务系统导出的课表。请你把课程逐条整理成 CSV，只输出 CSV 内容，不要解释。

        ## CSV 表头
        课程名,教师,地点,星期,开始节次,结束节次,周次,单双周

        ## 字段规则
        - 课程名：课程全名，去掉“*”、序号、教学班编号后缀。
        - 教师：一位或多位教师用“、”分隔；没有就留空。
        - 地点：教室/校区，没有就留空。
        - 星期：周一/周二/…/周日，或 1-7。
        - 开始节次/结束节次：整数，按学校作息表；跨节次填起止（如 3,4）。
        - 周次：支持 1-16、1-5,7-11、5-7周(单)、4-6周(双)、1-3周(单),4-6周(双),7-14周。
        - 单双周：可选“单/双”，如果周次里已经写了(单)/(双)就留空。
        - 同一门课有多个上课时间：输出多行，课程名/教师/地点可重复。
        - 同一节次不同周不同课程：分别输出多行。
        - 无法确定星期/节次的课程：不要编造，放到单独说明里告诉我。

        ## 示例
        课程名,教师,地点,星期,开始节次,结束节次,周次,单双周
        高等数学,张老师,公教2-509,周一,1,2,1-16,
        大学英语3,李老师,公教1-106,周三,3,4,"1-5,7-11",
        篮球初级班,王老师,田径场,周五,5,6,"5-7周(单),8-16周",

        ## 也可以用 JSON
        如果我更喜欢结构化格式，可以让我按 App 里「导出 JSON 模板」的 kexu-timetable/v1 结构输出；
        weekday 用 1-7（1=周一），weeks 用教学周表达式。两种格式只输出一种，不要混在一起。
    """.trimIndent()
}
